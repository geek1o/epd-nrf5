#!/usr/bin/env python3
"""Subset the repository's WenQuanYi BDFs with native U8g2 bdfconv."""
import argparse, pathlib, subprocess, tempfile
root = pathlib.Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser()
p.add_argument('--bdfconv', default='bdfconv')
a=p.parse_args()
# Printable ASCII, all 66 Russian letters including Ё/ё, degree sign.
codes=list(range(32,127))+[0x401]+list(range(0x410,0x450))+[0x451,0xb0]
text=''.join(chr(c) for c in sorted(codes))
(root/'tools/font_ru.txt').write_text(text+'\n')
parts=['/* Generated by tools/build_fonts_ru.py. WenQuanYi Bitmap Song: see tools/fonts/LICENSE-WenQuanYi.txt. */\n#include "fonts_ru.h"\n']
with tempfile.TemporaryDirectory() as tmp:
    for size in (9,12):
        name=f'u8g2_font_ru{size}'
        output=pathlib.Path(tmp)/'font.c'
        subprocess.run([a.bdfconv,'-b','0','-f','1','-m',','.join(str(c) for c in sorted(codes)),'-n',name,'-o',str(output),str(root/f'tools/fonts/wenquanyi_{size}ptb.bdf')],check=True)
        parts.append(output.read_text())
parts += [(root/f'tools/fonts/u8g2_font_helvB{size}_tn.c').read_text() for size in (14,18)]
(root/'GUI/fonts_ru.c').write_text('\n'.join(line.rstrip() for line in '\n'.join(parts).splitlines())+'\n')
