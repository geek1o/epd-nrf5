#!/usr/bin/env python3
"""Rasterize compact DejaVu Sans subsets and encode them with native U8g2 bdfconv."""
import argparse, pathlib, subprocess, tempfile
from PIL import Image, ImageDraw, ImageFont
root=pathlib.Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--bdfconv',default='bdfconv');a=p.parse_args()
codes=list(range(32,127))+[0x401]+list(range(0x410,0x450))+[0x451,0xb0]
(root/'tools/font_ru.txt').write_text(''.join(chr(c) for c in sorted(codes))+'\n')
fonts=[('u8g2_font_ru11',11,False,codes),('u8g2_font_ru13',13,False,codes),('u8g2_font_ru16',16,True,codes),('u8g2_font_ru_numbers20',20,True,list(range(48,58))),('u8g2_font_ru_numbers48',48,True,list(range(48,59)))]
parts=['/* Generated by tools/build_fonts_ru.py. DejaVu Sans: tools/fonts/LICENSE-DejaVu.txt. */\n#include "fonts_ru.h"\n']
with tempfile.TemporaryDirectory() as tmp:
 for name,size,bold,charset in fonts:
  source=root/'tools/fonts'/('DejaVuSans-Bold-RU.ttf' if bold else 'DejaVuSans-RU.ttf')
  font=ImageFont.truetype(str(source),size);ascent,descent=font.getmetrics()
  lines=['STARTFONT 2.1',f'FONT -dejavu-sans-{ "bold" if bold else "medium"}-r-normal--{size}-0-75-75-p-0-iso10646-1',f'SIZE {size} 75 75',f'FONTBOUNDINGBOX {size*2} {ascent+descent} 0 {-descent}','STARTPROPERTIES 3','COPYRIGHT "Copyright (c) 2003 Bitstream, Inc.; DejaVu changes are public domain. See LICENSE-DejaVu.txt."',f'FONT_ASCENT {ascent}',f'FONT_DESCENT {descent}','ENDPROPERTIES',f'CHARS {len(charset)}']
  for cp in sorted(charset):
   ch=chr(cp);x0,y0,x1,y1=font.getbbox(ch,anchor='ls');w,h=x1-x0,y1-y0
   advance=round(font.getlength(ch))
   im=Image.new('L',(max(w,1),max(h,1)))
   ImageDraw.Draw(im).text((-x0,-y0),ch,font=font,fill=255,anchor='ls')
   lines += [f'STARTCHAR uni{cp:04X}',f'ENCODING {cp}',f'SWIDTH {round(advance*1000/size)} 0',f'DWIDTH {advance} 0',f'BBX {w} {h} {x0} {-y1}','BITMAP']
   for y in range(h):
    bits=''.join('1' if im.getpixel((x,y))>=128 else '0' for x in range(w));bits+='0'*((-w)%8)
    lines.append(f'{int(bits or "0",2):0{max(len(bits)//4,2)}X}')
   lines.append('ENDCHAR')
  lines.append('ENDFONT');bdf=root/f'tools/fonts/{name}.bdf';bdf.write_text('\n'.join(lines)+'\n')
  output=pathlib.Path(tmp)/(name+'.c')
  subprocess.run([a.bdfconv,'-b','0','-f','1','-m',','.join(map(str,sorted(charset))),'-n',name,'-o',str(output),str(bdf)],check=True)
  parts.append(output.read_text())
parts.append((root/'tools/fonts/u8g2_font_helvB18_tn.c').read_text())
(root/'GUI/fonts_ru.c').write_text('\n'.join(line.rstrip() for line in '\n'.join(parts).splitlines())+'\n')
(root/'GUI/fonts_ru.h').write_text('#ifndef EPD_FONTS_RU_H\n#define EPD_FONTS_RU_H\n#include "u8g2_font.h"\n'+''.join(f'extern const uint8_t {name}[];\n' for name,_,_,_ in fonts)+'extern const uint8_t u8g2_font_helvB18_tn[];\n#endif\n')
